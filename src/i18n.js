let activeUiLanguage = "zh-CN";

function normalizeUiLanguage(value) {
  return UI_LANGUAGE_OPTIONS.includes(value) ? value : "auto";
}

function resolveUiLanguage(preference = "auto", detected = "") {
  const normalized = normalizeUiLanguage(preference);
  if (normalized !== "auto") return normalized;
  let candidate = String(detected || "").trim();
  if (!candidate) {
    try { candidate = String(globalThis.document?.documentElement?.lang || ""); } catch (e) {}
  }
  if (!candidate) {
    try { candidate = String(globalThis.navigator?.language || ""); } catch (e) {}
  }
  return /^zh(?:-|$)/i.test(candidate) ? "zh-CN" : "en";
}

function setUiLanguage(preference = "auto", detected = "") {
  activeUiLanguage = resolveUiLanguage(preference, detected);
  return activeUiLanguage;
}

function getUiLanguage() {
  return activeUiLanguage;
}

function interpolate(template, variables) {
  if (!variables) return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (whole, name) =>
    Object.prototype.hasOwnProperty.call(variables, name)
      ? String(variables[name])
      : whole
  );
}

function t(key, variables = null) {
  const current = MESSAGES[activeUiLanguage] || MESSAGES.en;
  const value = current[key] ?? MESSAGES["zh-CN"][key] ?? key;
  return interpolate(value, variables);
}

function languageName(code, fallback = "") {
  if (activeUiLanguage === "en") return ENGLISH_LANGUAGE_NAMES[code] || fallback || code;
  return fallback || code;
}

function providerName(name) {
  if (activeUiLanguage === "en") return ENGLISH_PROVIDER_NAMES[name] || name;
  return name;
}

function phaseName(name) {
  if (activeUiLanguage === "en") return ENGLISH_PHASE_NAMES[name] || name;
  return name;
}

function validateMessageCatalogs() {
  const locales = Object.keys(MESSAGES);
  const baseLocale = locales[0];
  const baseKeys = Object.keys(MESSAGES[baseLocale]).sort();
  const baseSet = new Set(baseKeys);
  const placeholders = (value) =>
    [...String(value).matchAll(/\{([A-Za-z0-9_]+)\}/g)]
      .map((match) => match[1])
      .sort()
      .join(",");
  const errors = [];
  for (const locale of locales.slice(1)) {
    const catalog = MESSAGES[locale];
    for (const key of baseKeys) {
      if (!Object.prototype.hasOwnProperty.call(catalog, key)) {
        errors.push(`${locale}: missing ${key}`);
      } else if (placeholders(catalog[key]) !== placeholders(MESSAGES[baseLocale][key])) {
        errors.push(`${locale}: placeholder mismatch for ${key}`);
      }
    }
    for (const key of Object.keys(catalog)) {
      if (!baseSet.has(key)) errors.push(`${locale}: unexpected ${key}`);
    }
  }
  return errors;
}

function hasMessageKey(key) {
  return Object.values(MESSAGES).every((catalog) =>
    Object.prototype.hasOwnProperty.call(catalog, key)
  );
}

module.exports = {
  UI_LANGUAGE_OPTIONS,
  normalizeUiLanguage,
  resolveUiLanguage,
  setUiLanguage,
  getUiLanguage,
  t,
  languageName,
  providerName,
  phaseName,
  validateMessageCatalogs,
  hasMessageKey,
};
